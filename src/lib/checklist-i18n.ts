export type ChecklistLang = "pt" | "en" | "es" | "fr";

export function resolveLang(value?: string): ChecklistLang {
  const v = (value || "").toLowerCase();
  if (v.startsWith("en")) return "en";
  if (v.startsWith("es") || v.includes("español") || v.includes("espanol")) return "es";
  if (v.startsWith("fr") || v.includes("français") || v.includes("francais")) return "fr";
  return "pt";
}

